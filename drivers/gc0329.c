int gc0329_init(void) {
    int i = 0; rt_uint8_t buf;
    rt_kprintf("Init GC0329...\n");
    while (gc0329_regs[i].addr != 0xff) {
        buf = gc0329_regs[i].addr; 
        buf = gc0329_regs[i].val;
        if (camera_i2c_write(GC0329_I2C_ADDR, buf, 2) != RT_EOK) return -1;
        i++; rt_thread_mdelay(1);
    }
    return 0;
}